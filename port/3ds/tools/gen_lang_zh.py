#!/usr/bin/env python3
"""Simplified Chinese for the bottom screen (Settings > Language > 简体中文).

The translations live in localization/ui_translations_zh_CN.csv (by
Darth-Koopa, GitHub PR #62 and their StarHaven_CN fork), keyed by the English
text as pm3ds_lang_table.inc has it. This writes:

  source/platform/pm3ds_lang_zh.inc   ZH("English", "中文") for pm3ds_lang.c
  source/platform/pm3ds_cjk_font.inc  every character those strings use, from
                                      Fusion Pixel (SIL OFL 1.1, fonts/OFL.txt)
                                      at 10 px (small text) and 12 px

The game's font has no Chinese, and most 3DS system fonts have no Simplified
Chinese (only Chinese consoles do), so the characters come with the program.
Both files are committed: the build needs neither Python packages nor fonts.

  gen_lang_zh.py --font10 fusion-pixel-10px-proportional-zh_hans.ttf \\
                 --font12 fusion-pixel-12px-proportional-zh_hans.ttf
      both files (needs Pillow; the fonts are in the release zips of
      https://github.com/TakWolf/fusion-pixel-font, 2026.10.25 used)
  gen_lang_zh.py
      only the strings; fails if one uses a character the font file lacks
"""
import argparse
import ast
import csv
import re
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
CSV = PORT / "localization" / "ui_translations_zh_CN.csv"
TABLE = PORT / "source" / "platform" / "pm3ds_lang_table.inc"
OUT_STR = PORT / "source" / "platform" / "pm3ds_lang_zh.inc"
OUT_FONT = PORT / "source" / "platform" / "pm3ds_cjk_font.inc"
EXTRA = "简体中文♪♥☆○"                   # the language's own name (pm3ds_lang.c); file-name symbols (GitHub #85)
PLACEHOLDER = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?[a-zA-Z]")


def c_string(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def table_keys():
    keys = []
    for m in re.finditer(r'^TR\(("(?:[^"\\]|\\.)*")', TABLE.read_text(encoding="utf-8"), re.M):
        keys.append(ast.literal_eval(m.group(1)))   # the table's C string literals read as Python ones
    return keys


def translations():
    rows, seen, bad = [], set(), 0
    with open(CSV, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            en, zh = r["english_source"], (r["proposed_simplified_chinese"] or "").strip()
            if not en or not zh or en in seen:
                continue              # one English text, one translation: the first row
            if PLACEHOLDER.findall(en) != PLACEHOLDER.findall(zh):
                print(f"skipped (its %-codes differ): {en!r} -> {zh!r}", file=sys.stderr)
                bad += 1
                continue
            seen.add(en)
            rows.append((en, zh))
    return rows, bad


def chars_of(rows):
    cps = {ord(c) for _, zh in rows for c in zh if ord(c) >= 0x80}
    cps |= {ord(c) for c in EXTRA}
    # Latin letters, digits and signs: a phrase with Chinese in it is drawn in this
    # font all through (bottom_screen.c has_cjk, GitHub #85)
    cps |= set(range(0x20, 0x7F))
    return sorted(cps)


def font_chars():
    if not OUT_FONT.exists():
        return set()
    m = re.search(r"pm3ds_cjk_cp\[\] = \{(.*?)\};", OUT_FONT.read_text(), re.S)
    return {int(x, 16) for x in re.findall(r"0x([0-9A-F]+)", m.group(1))} if m else set()


def render(path, size, cps):
    """each character as 16 rows of 16 bits (MSB left), its pen advance"""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(str(path), size)
    asc, _ = font.getmetrics()
    rows, adv, missing = [], [], []
    for cp in cps:
        ch = chr(cp)
        img = Image.new("L", (24, 24), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        bits = []
        for y in range(16):
            v = 0
            for x in range(16):
                if img.getpixel((x, y)) >= 128:
                    v |= 0x8000 >> x
            bits.append(v)
        if not any(bits) and not ch.isspace():
            missing.append(ch)
        rows.append(bits)
        adv.append(max(1, round(font.getlength(ch))))
    if missing:
        sys.exit(f"{path.name} lacks: {''.join(missing)}")
    return rows, adv, asc


def write_font(cps, f10, f12):
    lines = [
        "/* generated by tools/gen_lang_zh.py: do not edit. The characters of the",
        " * Simplified Chinese strings, from Fusion Pixel (TakWolf, SIL Open Font",
        " * License 1.1, port/3ds/fonts/OFL.txt), 16 rows of 16 bits (MSB left) each. */",
        f"#define PM3DS_CJK_CHARS {len(cps)}",
        "static const uint16_t pm3ds_cjk_cp[] = {",
    ]
    row = [f"0x{cp:04X}," for cp in cps]
    lines += ["    " + " ".join(row[i:i + 12]) for i in range(0, len(row), 12)]
    lines.append("};")
    for size, path in ((10, f10), (12, f12)):
        bits, adv, asc = render(path, size, cps)
        lines.append(f"#define PM3DS_CJK{size}_ASCENT {asc}")
        lines.append(f"static const uint8_t pm3ds_cjk{size}_adv[] = {{")
        row = [f"{a}," for a in adv]
        lines += ["    " + " ".join(row[i:i + 24]) for i in range(0, len(row), 24)]
        lines.append("};")
        lines.append(f"static const uint16_t pm3ds_cjk{size}_bits[][16] = {{")
        for cp, b in zip(cps, bits):
            lines.append("    {" + ",".join(f"0x{v:04X}" for v in b) + f"}},  /* {chr(cp)} */")
        lines.append("};")
    OUT_FONT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font10", type=Path)
    ap.add_argument("--font12", type=Path)
    a = ap.parse_args()

    rows, bad = translations()
    keys = table_keys()
    have = {en for en, _ in rows}
    missing = [k for k in keys if k not in have]
    lines = ["/* generated by tools/gen_lang_zh.py from localization/ui_translations_zh_CN.csv: do not edit */"]
    lines += [f"ZH({c_string(en)}, {c_string(zh)})" for en, zh in rows]
    OUT_STR.write_text("\n".join(lines) + "\n", encoding="utf-8")

    cps = chars_of(rows)
    if a.font10 and a.font12:
        write_font(cps, a.font10, a.font12)
    elif a.font10 or a.font12:
        sys.exit("give both --font10 and --font12")
    else:
        lack = [chr(c) for c in cps if c not in font_chars()]
        if lack:
            sys.exit(f"{OUT_FONT.name} lacks {''.join(lack)}: run with --font10/--font12")
    print(f"{len(rows)} translations ({len(keys) - len(missing)} of the table's {len(keys)}, "
          f"{len(rows) - (len(keys) - len(missing))} for other UI text), {len(cps)} characters"
          + (f", {bad} skipped" if bad else ""))
    if missing:
        print("not translated yet:", "; ".join(missing))


if __name__ == "__main__":
    main()
