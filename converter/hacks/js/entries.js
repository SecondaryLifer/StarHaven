// entries.js: port of tools/hackrecomp/entries.py (see its docstring): copies
// of recompiled functions that start at an entry into their middle, and the
// table the runtime looks them up in.

const HEAD = /^RECOMP_FUNC void (\w+)\(uint8_t\* rdram, recomp_context\* ctx\) \{$/;
const hex8 = (v) => v.toString(16).toUpperCase().padStart(8, "0");

/** funcFiles: {name: text} of N64Recomp's funcs_*.c -> {name: [lines]} */
export function bodies(funcFiles) {
    const out = {};
    for (const [path, text] of Object.entries(funcFiles)) {
        if (path.endsWith("funcs_entries.c") || path.endsWith("funcs_hle.c")) continue;
        const lines = text.split("\n");
        for (let i = 0; i < lines.length; i++) {
            const m = HEAD.exec(lines[i]);
            if (!m) continue;
            let j = i + 1;
            while (j < lines.length && lines[j] !== ";}") j++;
            out[m[1]] = lines.slice(i, j + 1);
            i = j;
        }
    }
    return out;
}

/**
 * entries: discover's list; funcs: bodies(). One copy per function that takes
 * the entry's index, and a function per address calling it (as entries.py).
 * -> {"funcs/funcs_entries.c", "entry_table.inc", summary}
 */
export function writeEntries(entries, funcs) {
    const code = ['#include "recomp.h"', '#include "funcs.h"', ""];
    const table = [];
    let missing = 0;
    const byFunc = new Map();
    for (let [fname, , vram] of entries) {
        if (!funcs[fname]) fname += "_recomp";
        if (!funcs[fname]) { missing++; continue; }
        if (!byFunc.has(fname)) byFunc.set(fname, []);
        if (!byFunc.get(fname).includes(vram)) byFunc.get(fname).push(vram);
    }
    for (const [fname, vrams] of byFunc) {
        const body = funcs[fname];
        const base = HEAD.exec(body[0])[1];
        const labels = [];
        for (const vram of vrams) {
            const marker = `    // 0x${hex8(vram)}:`;
            let last = -1;
            body.forEach((l, k) => { if (l.startsWith(marker)) last = k; });
            if (last < 0) { missing++; continue; }
            labels.push([last, vram]);
        }
        if (!labels.length) continue;
        const copy = [...body];
        for (const [line, vram] of [...labels].sort((a, b) => b[0] - a[0] || b[1] - a[1])) copy.splice(line, 0, `L_entry_${hex8(vram)}:`);
        copy[0] = `static void ${base}__entries(uint8_t* rdram, recomp_context* ctx, int entry) {`;
        const k = copy.findIndex((l) => l.trim() === "int c1cs = 0;");
        copy.splice(k + 1, 0, "    switch (entry) {", ...labels.map(([, v], i) => `        case ${i}: goto L_entry_${hex8(v)};`), "    }");
        code.push(...copy, "");
        labels.forEach(([, vram], i) => {
            const name = `${base}__at_${hex8(vram)}`;
            code.push(`RECOMP_FUNC void ${name}(uint8_t* rdram, recomp_context* ctx) { ${base}__entries(rdram, ctx, ${i}); }`);
            table.push([vram, name]);
        });
        code.push("");
    }
    table.sort((a, b) => a[0] - b[0] || (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0));
    const t = ["/* generated by entries.py: entries into the middle of functions */"]
        .concat(table.map(([, n]) => `void ${n}(uint8_t* rdram, recomp_context* ctx);`),
            ["static const struct { uint32_t vram; recomp_func_t *f; } entry_table[] = {"],
            table.map(([v, n]) => `    { 0x${hex8(v)}u, ${n} },`),
            ["    { 0xFFFFFFFFu, 0 },", "};"]);
    return {
        "funcs/funcs_entries.c": code.join("\n") + "\n",
        "entry_table.inc": t.join("\n") + "\n",
        summary: `${table.length} entry points written, ${missing} not found`,
    };
}
