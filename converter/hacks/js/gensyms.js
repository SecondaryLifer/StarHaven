// gensyms.js: port of tools/hackrecomp/gen_syms.py (see its docstring).
// Returns the files it writes, {path: text}, paths relative to the output folder.

const PURE_OS = new Set([
    "bcmp", "bcopy", "bzero", "coss", "crc", "frustum", "guLookAt", "guMtxCat", "guMtxCatF",
    "guMtxF2L", "guMtxIdentF", "guMtxIdent", "guMtxL2F", "guMtxXFMF", "guMtxXFML", "guNormalize", "guOrtho",
    "guRotate", "guScaleF", "guScale", "guTranslateF", "guTranslate", "ldiv", "lookathil", "lookatref",
    "memset", "perspective", "position", "rotateRPY", "sins", "sprintf", "sqrtf", "strcmp", "strcpy", "string",
    "xldtob", "xlitob", "xprintf",
]);
const SKIP_SEGMENTS = new Set(["header", "boot"]);
const SKIP_PREFIXES = ["dead_"];
const LIBC_NAMES = new Set(["atan2", "bcmp", "bcopy", "bzero", "ldiv", "lldiv", "memcpy", "memset", "printf", "round",
    "sprintf", "sqrtf", "strchr", "strcmp", "strcpy", "strlen"]);
const IDLE_LOOP = 0x1000FFFF;
const SYSCALL = 0x0000000C;

const hex = (v, n = 0) => v.toString(16).toUpperCase().padStart(n, "0");
const u32 = (b, o) => ((b[o] << 24) | (b[o + 1] << 16) | (b[o + 2] << 8) | b[o + 3]) >>> 0;
const cmpStr = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function isHle(obj) {
    if (!obj.startsWith("src/os/")) return false;
    let base = obj.slice(obj.lastIndexOf("/") + 1);
    for (const ext of [".c", ".s"]) if (base.endsWith(ext)) base = base.slice(0, -ext.length);
    return !obj.startsWith("src/os/nusys/") && !PURE_OS.has(base);
}

/**
 * van: elfinfo.py's json; rom: the ROM (Uint8Array); romPath: the ROM's path
 * as N64Recomp will see it; extra: discover's json (or {} for vanilla).
 */
export function genSyms(van, rom, romPath, extra = {}) {
    extra = { sections: [], replace: [], add: {}, entries: [], resize: {}, drop: {}, ...extra };
    const replaced = new Set(extra.replace);
    const sections = [];
    for (const s of van.segments) {
        if (SKIP_SEGMENTS.has(s.name) || SKIP_PREFIXES.some((p) => s.name.startsWith(p)) || !s.functions.length || replaced.has(s.name)) continue;
        const resize = extra.resize[s.name] || {};
        const drop = new Set(extra.drop[s.name] || []);
        let fl = s.functions.filter((f) => !drop.has(f[0])).map((f) => [f[0], f[1], f[0] in resize ? resize[f[0]] : f[2], f[3]]);
        fl = fl.concat((extra.add[s.name] || []).map((f) => [f[0], f[1], f[2], ""]));
        fl.sort((a, b) => a[1] - b[1]);          // stable, like Python's sorted
        sections.push({ name: s.name, rom: s.rom, vram: s.vram, size: s.size, functions: fl });
    }
    for (const s of extra.sections)
        sections.push({ name: s.name, rom: s.rom, vram: s.vram, size: s.size, functions: s.functions.map((f) => [f[0], f[1], f[2], ""]) });

    const ignored = [], patches = [], lines = [];
    const hleVram = new Map();
    const seen = new Set();
    for (const s of sections) {
        lines.push("[[section]]", `name = "${s.name}"`, `rom = 0x${hex(s.rom, 8)}`, `vram = 0x${hex(s.vram, 8)}`, `size = 0x${hex(s.size)}`, "");
        for (let [name, vram, size, obj] of s.functions) {
            if (isHle(obj)) {
                name += "_recomp";
                ignored.push(name);
                hleVram.set(name, vram);
            } else if (LIBC_NAMES.has(name)) name += "_pm";
            if (seen.has(name)) name = `${name}_${s.name}`;
            seen.add(name);
            lines.push("[[section.functions]]", `name = "${name}"`, `vram = 0x${hex(vram, 8)}`, `size = 0x${hex(size)}`, "");
            if (obj.startsWith("src/os/") && !isHle(obj)) continue;
            for (let off = 0; off < size - 4; off += 4) {
                const r = s.rom + (vram - s.vram) + off;
                if (r + 4 <= rom.length && u32(rom, r) === IDLE_LOOP) patches.push([name, vram + off]);
            }
        }
    }
    const files = {};
    files["syms.toml"] = lines.join("\n");

    let cfg = ["[input]", "entrypoint = 0x80025C00", 'symbols_file_path = "syms.toml"',
        `rom_file_path = "${romPath}"`, 'output_func_path = "funcs"',
        'recomp_include = "#include \\"recomp.h\\""', "functions_per_output_file = 64", "",
        "[patches]", "ignored = ["].concat(ignored.map((n) => `    "${n}",`), ["]", ""]);
    for (const [name, vram] of patches)
        cfg.push("[[patches.instruction]]", `func = "${name}"`, `vram = 0x${hex(vram, 8)}`, `value = 0x${hex(SYSCALL, 8)}`, "");
    files["recomp.toml"] = cfg.join("\n");
    const ign = [...ignored].sort(cmpStr);
    files["hle_funcs.json"] = ign.length ? "[\n" + ign.map((n) => JSON.stringify(n)).join(",\n") + "\n]" : "[]";
    files["entries.json"] = pyJson(extra.entries);
    const decl = ["/* generated by gen_syms.py: libultra, provided by the runtime */", '#include "recomp.h"']
        .concat(ign.map((n) => `void ${n}(uint8_t *rdram, recomp_context *ctx);`));
    files["hle_decls.h"] = decl.join("\n") + "\n";
    const tab = ['#include "hle_decls.h"', "static const struct { uint32_t vram; recomp_func_t *f; } hle_table[] = {"]
        .concat([...hleVram].sort((a, b) => a[1] - b[1]).map(([n, v]) => `    { 0x${hex(v, 8)}u, ${n} },`), ["};"]);
    files["hle_table.inc"] = tab.join("\n") + "\n";
    const stubs = ['#include "hle_decls.h"', "void rt_fatal(const char *fmt, ...) __attribute__((noreturn));"]
        .concat(ign.map((n) => `__attribute__((weak)) void ${n}(uint8_t *rdram, recomp_context *ctx) ` +
            `{ (void)rdram; (void)ctx; rt_fatal("libultra ${n.slice(0, -7)} is not implemented"); }`));
    files["funcs/funcs_hle.c"] = stubs.join("\n") + "\n";
    const nf = sections.reduce((a, s) => a + s.functions.length, 0);
    files.summary = `${sections.length} sections, ${nf} functions, ${ignored.length} for the runtime, ${patches.length} idle loops`;
    return files;
}

/** json.dump's default formatting (", " and ": ") for lists of numbers and strings */
function pyJson(v) {
    if (Array.isArray(v)) return "[" + v.map(pyJson).join(", ") + "]";
    return JSON.stringify(v);
}
