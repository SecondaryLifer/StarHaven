#!/usr/bin/env python3
"""iQue (Chinese) font: glyph index <-> Unicode, for the bottom screen.

The iQue ROM's messages write a Chinese character as two bytes, a lead byte
0x5F..0x8F and a trail byte from 1; src/msg_draw.c turns them into an index in
charset/standard.dat:

    glyph = (MSG_CHAR_ZH_START - MSG_CHAR_MULTIBYTE_FIRST) + lead
            + (trail - 1) * (MSG_CHAR_MULTIBYTE_LAST - MSG_CHAR_MULTIBYTE_FIRST + 1)

tools/splat_ext/pm_msg.py's CHARSET_IQUE says which character each pair is.
This writes source/n64_shim/ique_charmap.inc (no ROM needed): the code point
of every glyph, and the glyph of every code point, so the bottom screen keeps
its text in Unicode (n64_shim/touch_menu.c) and draws it with the ROM's font
(platform/bottom_screen.c).

usage: gen_ique_charmap.py   (from anywhere; paths are the repo's)
"""
import ast
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
REPO = PORT.parent.parent
PM_MSG = REPO / "tools" / "splat_ext" / "pm_msg.py"
OUT = PORT / "source" / "n64_shim" / "ique_charmap.inc"

MULTIBYTE_FIRST, MULTIBYTE_LAST, ZH_START = 0x5F, 0x8F, 0xA6   # include/enums.h
GLYPHS = 0x4F000 // 0x80                                        # charset/standard.dat


def charset_ique():
    tree = ast.parse(PM_MSG.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "CHARSET_IQUE":
            return node.value
    sys.exit("CHARSET_IQUE not found in " + str(PM_MSG))


def main():
    table = charset_ique()
    glyph_cp = {}
    for key, val in zip(table.keys, table.values):
        if key is None or not isinstance(val, ast.Dict):
            continue                      # **CHARSET_COMMON: the one-byte codes, as in the US font
        lead = ast.literal_eval(key)
        for tkey, tval in zip(val.keys, val.values):
            trail, ch = ast.literal_eval(tkey), ast.literal_eval(tval)
            if not isinstance(ch, str) or len(ch) != 1:
                continue
            glyph = (ZH_START - MULTIBYTE_FIRST) + lead + (trail - 1) * (MULTIBYTE_LAST - MULTIBYTE_FIRST + 1)
            if not ZH_START <= glyph < GLYPHS:
                sys.exit(f"glyph {glyph:#x} of {lead:#x} {trail:#x} is outside the font")
            glyph_cp[glyph] = ord(ch)
    cp_glyph = {}
    for glyph in sorted(glyph_cp):
        cp_glyph.setdefault(glyph_cp[glyph], glyph)     # a character twice: the first glyph
    if max(cp_glyph) > 0xFFFFF or max(glyph_cp) > 0xFFF:
        sys.exit("a code point or glyph does not fit the packed table")

    last = max(glyph_cp)
    lines = [
        "/* generated by tools/gen_ique_charmap.py from tools/splat_ext/pm_msg.py (CHARSET_IQUE): do not edit */",
        f"#define PM3DS_IQUE_GLYPH_FIRST 0x{ZH_START:X}",
        f"#define PM3DS_IQUE_GLYPH_END 0x{last + 1:X}",
        f"#define PM3DS_IQUE_CHARS {len(cp_glyph)}",
        "/* the code point of glyph PM3DS_IQUE_GLYPH_FIRST + i (0: none) */",
        "static const uint16_t pm3ds_ique_glyph_cp[] = {",
    ]
    row = [f"0x{glyph_cp.get(g, 0):04X}," for g in range(ZH_START, last + 1)]
    lines += ["    " + " ".join(row[i:i + 12]) for i in range(0, len(row), 12)]
    lines += ["};", "/* code point << 12 | glyph, sorted: a binary search finds a character's glyph */",
              "static const uint32_t pm3ds_ique_cp_glyph[] = {"]
    row = [f"0x{cp << 12 | g:08X}," for cp, g in sorted(cp_glyph.items())]
    lines += ["    " + " ".join(row[i:i + 8]) for i in range(0, len(row), 8)]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(glyph_cp)} glyphs, {len(cp_glyph)} characters")


if __name__ == "__main__":
    main()
