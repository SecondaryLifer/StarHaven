#!/usr/bin/env python3
"""Link the PAL, US and iQue builds of the game into one program.

A release package runs with any of the three ROMs, but the decomp compiles
differently per version, so the program holds every build and
universal/starter.c picks one at run time from the ROM's header. Run inside
the papermario-3ds-builder image after the versions are built (make
PM3DS_GAME=1 for pal, then with PM3DS_VERSION=us and PM3DS_VERSION=ique); the
object lists come from their linker maps.

  * PAL copy: its objects as linked, main() renamed pal_main.
  * US and iQue copies: every global symbol their objects define, and every
    symbol their m11_syms_<v>.ld provides, gets a us_ / iq_ prefix (objcopy
    --redefine-syms), so the copies never bind to each other. Library symbols
    (libctru, citro3d, newlib, libgcc) and linker-script symbols stay shared.
    --wrap pairs keep working: __wrap_X -> __wrap_us_X, __real_X -> __real_us_X.
  * The copies' code is all loaded, but their data and zeroed globals share
    one area (universal/universal.ld): each copy's .data/.bss is linked at
    __pm3ds_copy_area in a section that isn't loaded, tools/package.sh puts
    its data in romfs and the starter loads the chosen copy's before calling
    it. Only one copy's data is ever in memory. Two links: the first measures
    the largest copy, the second sizes the area for it.
  * starter.o provides main().

usage (in the image): universal.py [out.elf]   (default port/3ds/StarHaven_universal.elf)
"""
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys

PORT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BIN = "/opt/devkitpro/devkitARM/bin/arm-none-eabi-"
CTRU = "/opt/devkitpro/libctru"
PORTLIBS = "/opt/devkitpro/portlibs/3ds"
ARCH = ["-march=armv6k", "-mtune=mpcore", "-mfloat-abi=hard", "-mtp=soft"]
WORK = os.path.join(PORT, "build_universal")
# (copy name in universal.ld, symbol prefix, build dir, map, link symbols)
COPIES = [
    ("pal", "", "build", "PaperMario3DS.map", "m11_syms.ld"),
    ("us", "us_", "build_us", "PaperMario3DS_us.map", "m11_syms_us.ld"),
    ("iq", "iq_", "build_ique", "PaperMario3DS_ique.map", "m11_syms_ique.ld"),
]


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit("failed: %s\n%s%s" % (" ".join(cmd[:6]), r.stdout[-3000:], r.stderr[-3000:]))
    return r.stdout


def linked_objects(build_dir, mapfile):
    """the objects a version's link used, from its map's LOAD lines"""
    out = []
    for line in open(os.path.join(build_dir, mapfile), errors="replace"):
        if line.startswith("LOAD "):
            p = line[5:].strip()
            if p.endswith(".o") and not p.startswith("/"):
                out.append(os.path.join(build_dir, p))
    return out


def global_symbols(objs):
    """(defined, undefined) global symbol names over a list of objects"""
    defined, undefined = set(), set()
    for i in range(0, len(objs), 400):
        for line in run([BIN + "nm", "-g", "--no-sort"] + objs[i:i + 400]).splitlines():
            p = line.split()
            if len(p) == 2 and p[0] in ("U", "w", "v"):
                undefined.add(p[1])
            elif len(p) == 3:
                defined.add(p[2])
    return defined, undefined


def provided(ldscript):
    return re.findall(r"PROVIDE\((\w+) = (\w+)\);", open(ldscript).read())


def prepare_copy(name, prefix, build, mapfile, ldsyms):
    """the copy's objects under build_universal/copy_<name>/ (renamed), and its link symbols"""
    build_dir = os.path.join(PORT, build)
    objs = linked_objects(build_dir, mapfile)
    provides = provided(os.path.join(PORT, ldsyms))
    if prefix:
        defined, undefined = global_symbols(objs)
        rename = {s: prefix + s for s in defined | {a for a, _ in provides}}
        for s in list(rename):
            if s.startswith("__wrap_"):
                rename[s] = "__wrap_" + prefix + s[len("__wrap_"):]
        for s in undefined:
            if s.startswith("__real_"):
                rename[s] = "__real_" + prefix + s[len("__real_"):]
    else:
        rename = {"main": "pal_main"}
    mapf = os.path.join(WORK, "%s_rename.txt" % name)
    with open(mapf, "w") as fh:
        fh.write("".join("%s %s\n" % kv for kv in sorted(rename.items())))
    out_dir = os.path.join(WORK, "copy_" + name)
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)

    def rewrite(src):
        dst = os.path.join(out_dir, os.path.relpath(src, build_dir))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        run([BIN + "objcopy", "--redefine-syms=" + mapf, src, dst])
        return dst
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 8) as ex:
        new = list(ex.map(rewrite, objs))
    ld = os.path.join(WORK, "%s_universal.ld" % os.path.splitext(ldsyms)[0])
    with open(ld, "w") as fh:
        fh.write("/* GENERATED by tools/universal.py from %s -- do not edit */\n" % ldsyms)
        for a, b in provides:
            fh.write("PROVIDE(%s = %s);\n" % (rename.get(a, a), rename.get(b, b)))
    print("%s copy: %d objects, %d symbols renamed" % (name, len(objs), len(rename)))
    return new, ld


def main():
    out_elf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(PORT, "StarHaven_universal.elf")
    os.makedirs(WORK, exist_ok=True)
    wraps = sorted(set(re.findall(r"--wrap=(\w+)", open(os.path.join(PORT, "Makefile")).read())))
    objs, lds = [], []
    for c in COPIES:
        o, ld = prepare_copy(*c)
        objs += o
        lds.append(ld)

    starter = os.path.join(WORK, "starter.o")
    run([BIN + "gcc", "-O2", "-g", "-Wall", "-mword-relocations", "-ffunction-sections", "-fdata-sections"] + ARCH +
        ["-D__3DS__", "-I" + os.path.join(PORT, "include"), "-I" + CTRU + "/include",
         "-I" + PORTLIBS + "/include", "-c", os.path.join(PORT, "universal", "starter.c"), "-o", starter])

    # 3dsx.specs with our linker script in place of 3dsx.ld
    specs = os.path.join(WORK, "universal.specs")
    with open(specs, "w") as fh:
        fh.write("%%include <sync-dmb.specs>\n\n*link:\n+ -T %s -d --emit-relocs --use-blx --gc-sections\n\n"
                 "*startfile:\n3dsx_crt0%%O%%s crti%%O%%s crtbegin%%O%%s\n" % os.path.join(PORT, "universal", "universal.ld"))
    rsp = os.path.join(WORK, "link.rsp")
    with open(rsp, "w") as fh:
        fh.write("\n".join([starter] + objs) + "\n")

    def link(area_size, out):
        run([BIN + "gcc", "-specs=" + specs, "-g"] + ARCH +
            ["-Wl,-Map," + os.path.join(WORK, "universal.map"), "-Wl,--defsym=__pm3ds_copy_size=0x%X" % area_size] +
            ["-Wl,--wrap=" + p + w for _, p, _, _, _ in COPIES for w in wraps] +
            ["@" + rsp] + lds +
            ["-L" + PORTLIBS + "/lib", "-lcurl", "-lmbedtls", "-lmbedx509", "-lmbedcrypto", "-lz",   # update check
             "-L" + CTRU + "/lib", "-lcitro3d", "-lctru", "-lm", "-o", out])

    def syms(elf):
        out = {}
        for line in run([BIN + "nm", elf]).splitlines():
            p = line.split()
            if len(p) == 3 and p[2].startswith("__pm3ds_copy_"):
                out[p[2]] = int(p[0], 16)
        return out

    # pass 1: room for anything, to measure; pass 2: the largest copy's size
    link(0x4000000, out_elf)
    s = syms(out_elf)
    need = max(s["__pm3ds_copy_%s_end" % c[0]] for c in COPIES) - s["__pm3ds_copy_area"]
    need = (need + 0xFFF) & ~0xFFF
    link(need, out_elf)
    s = syms(out_elf)
    for c in COPIES:
        print("  %s copy: data + bss %.2f MB" % (c[0], (s["__pm3ds_copy_%s_end" % c[0]] - s["__pm3ds_copy_area"]) / 1048576))
    print("linked %s, copy area %.2f MB at 0x%X" % (out_elf, need / 1048576, s["__pm3ds_copy_area"]))
    print(run([BIN + "size", out_elf]))


if __name__ == "__main__":
    main()
